import pandas as pd

# 1. 读取刚才清洗好的数据表格
df = pd.read_csv("../logs/financial_data.csv")

# 2. 数据清洗：去掉逗号，转为真正的浮点数（数字）
# 大白话：把 "53,909,252,220.51" 变成 53909252220.51，方便做数学计算
df["数值_纯数字"] = df["数值"].astype(str).str.replace(",", "", regex=False).astype(float)

print("--- 数据清洗成功！看看现在纯数字的样子 ---")
print(df[["财务指标", "数值_纯数字"]].head())

print("\n--- 开始运行核验报警系统 ---")

# 3. 我们准备一个“标准答案”（模拟队友C提供的正确数据）
# 假设我们从原始财务报表里，人工核对确认，茅台的营业收入应该是 53,909,252,220.51
标准答案 = {
    "营业收入": 53909252220.51,
    "总资产": 319918844905.58
}

# 4. 设定一个“容差范围”（也就是允许的误差值）
# 在真实金融业务中，差一分钱也可能算错，但为了测试，我们允许差 1000 块钱
容差范围 = 1000.0

# 5. 遍历表格里的每一行，进行核对
for index, row in df.iterrows():
    # 提取当前的财务指标名称
    指标 = row["财务指标"]
    # 提取当前的纯数字
    报告值 = row["数值_纯数字"]
    
    # 如果这个指标在我们的“标准答案”字典里
    if 指标 in 标准答案:
        标准值 = 标准答案[指标]
        
        # 计算差值
        差值 = abs(报告值 - 标准值)
        
        # 如果差值超出了容差范围
        if 差值 > 容差范围:
            print(f"🚨 【报警】发现错误！指标：{指标}")
            print(f"  报告写的是：{报告值}")
            print(f"  正确应该是：{标准值}")
            print(f"  差值：{差值}\n")
        else:
            print(f"✅ 【通过】{指标} 数据准确，无异常。")

# 6. 测试报警系统
# 我们来“故意制造一个错误”，看看系统能不能发现
print("\n--- 模拟测试：如果我们故意把报告的营业收入改错，系统能发现吗？ ---")

# 故意把表格里的营业收入改成一个错误的值
df.loc[df["财务指标"] == "营业收入", "数值_纯数字"] = 52909252220.51 

# 重新遍历一遍
for index, row in df.iterrows():
    指标 = row["财务指标"]
    报告值 = row["数值_纯数字"]
    if 指标 in 标准答案:
        标准值 = 标准答案[指标]
        if abs(报告值 - 标准值) > 容差范围:
            print(f"🚨 【报警】发现错误！指标：{指标}")
            print(f"  报告写的是：{报告值}")
            print(f"  正确应该是：{标准值}")
            print(f"  修改建议：请核对原始财报数据来源。\n")